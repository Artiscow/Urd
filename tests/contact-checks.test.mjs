test('every check has cases, and every case is a check', () => {
  assert.deepEqual(Object.keys(CHECKS).sort(), Object.keys(CASES).sort());
});

for (const [name, { ok, bad }] of Object.entries(CASES)) {
  test(`${name}: the published numbers pass and a changed digit fails`, () => {
    for (const n of ok) assert.equal(runCheck(name, n), true, `${name} ${n}`);
    for (const n of bad) assert.equal(runCheck(name, n), false, `${name} ${n}`);
  });
}

test('gb-vat: the remainder 55 that python-stdnum accepts is not refused (a constructed number, none published)', () => {
  // 1000000 weighted 8..2 gives 8; 8 + 47 = 55.
  assert.equal(runCheck('gb-vat', '100000047'), true);
});

test('runCheck: an unknown check passes, and a throwing check fails', () => {
  assert.equal(runCheck('none-such', '123'), true);
  assert.equal(runCheck('ru-ogrn', 'abc'), false);
});
